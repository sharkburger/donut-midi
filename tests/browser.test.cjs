const { chromium } = require('playwright');
(async()=>{
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage();
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:18088/play.html');
 const frame=page;await frame.locator('canvas').first().waitFor();
 await frame.locator('#audioButton').click();
 await frame.locator('[data-phase=look]').click();
 const canvas=await frame.locator('canvas').first().boundingBox();
 await page.mouse.move(canvas.x+canvas.width*.23,canvas.y+canvas.height*.43);
 await page.waitForTimeout(700);
 const desktop=await page.evaluate(()=>window.donutDebug());
 if(desktop.noteCount<1)throw Error('Desktop dwell did not play');
 await frame.locator('#source').selectOption('replay');
 await frame.locator('#demoReplay').click();await frame.locator('#playReplay').click();
 await page.waitForTimeout(700);
 if(!await page.evaluate(()=>window.donutDebug().replayPlaying))throw Error('Replay not running');
 await page.screenshot({path:'build/desktop-beta.png',fullPage:true});
 const context=await browser.newContext({viewport:{width:390,height:844},hasTouch:true,isMobile:true});
 const mobile=await context.newPage();mobile.on('pageerror',e=>errors.push(e.message));
 await mobile.goto('http://127.0.0.1:18088/play.html');
 await mobile.locator('canvas').first().waitFor();
 await mobile.locator('#audioButton').click();await mobile.locator('[data-phase=look]').click();
 await mobile.locator('canvas').first().scrollIntoViewIfNeeded();
 const c=await mobile.locator('canvas').first().boundingBox();
 const client=await context.newCDPSession(mobile);
 const x=c.x+c.width*.23,y=c.y+c.height*.43;
 await client.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x,y}]});await mobile.waitForTimeout(700);
 const first=await mobile.evaluate(()=>window.donutDebug().noteCount);
 await client.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});await mobile.waitForTimeout(100);
 await client.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x,y}]});await mobile.waitForTimeout(700);
 const second=await mobile.evaluate(()=>window.donutDebug().noteCount);
 await client.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
 if(first!==1||second!==2)throw Error('Touch dwell/retrigger failed '+first+'/'+second);
 await mobile.locator('#recordConsent').check();await mobile.locator('#record').click();await mobile.waitForTimeout(200);await mobile.locator('#record').click();
 const [download]=await Promise.all([mobile.waitForEvent('download'),mobile.locator('#export').click()]);
 await download.saveAs('build/test-recording.json');
 await mobile.locator('#source').selectOption('replay');
 await mobile.locator('#replayFile').setInputFiles('build/test-recording.json');
 await mobile.waitForTimeout(200);
 if(!(await mobile.locator('#replayInfo').textContent()).includes('已加载'))throw Error('Import failed');
 await mobile.screenshot({path:'build/mobile-beta.png',fullPage:true});
 console.log(JSON.stringify({desktopNotes:desktop.noteCount,touchNotes:[first,second],errors}));
 await browser.close();if(errors.length)process.exit(1);
})().catch(e=>{console.error(e);process.exit(1)});
