const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
(async()=>{
 const browser=await chromium.launch({headless:true});
 const context=await browser.newContext({viewport:{width:390,height:844},hasTouch:true,isMobile:true});
 const page=await context.newPage();const errors=[];page.on('pageerror',e=>{errors.push(e.message);console.log('PAGE ERROR',e.stack);});
 await page.addInitScript(()=>{window.webkit={messageHandlers:{exportRecording:{postMessage:text=>window.testExport=text}}};});
 await page.goto('http://127.0.0.1:18089/');
 await page.locator('#scoreMode').getByText('Touch · hold to play').waitFor();
 assert.deepEqual(errors,[]);assert.equal(await page.locator('#source option[value=live]').count(),0);
 assert.equal(await page.locator('#openWorkshop').isVisible(),false);
 await page.locator('#audioButton').click();
 const canvas=page.locator('#canvasHost canvas');await canvas.scrollIntoViewIfNeeded();
 const box=await canvas.boundingBox();assert.ok(box.width>250);
 const client=await context.newCDPSession(page);
 const x=box.x+box.width*.185,y=box.y+box.height*.32;
 const touch=async()=>{const before=await page.evaluate(()=>window.donutDebug().noteCount);await client.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x,y}]});await page.waitForFunction(n=>window.donutDebug().noteCount>n,before,{timeout:3000});await page.waitForTimeout(200);await client.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});await page.waitForTimeout(100);};
 await touch();const first=await page.evaluate(()=>window.donutDebug().noteCount);
 await touch();const second=await page.evaluate(()=>window.donutDebug().noteCount);
 assert.equal(first,1);assert.equal(second,2);
 await page.locator('[data-panel=research]').click();
 await page.locator('#recordConsent').check();await page.locator('#record').click();await page.waitForTimeout(200);await page.locator('#record').click();await page.locator('#export').click();
 const record=await page.evaluate(()=>window.testExport);assert.equal(JSON.parse(record).schema,'donut-song/1');assert.equal(JSON.parse(record).source,'simulate');
 assert.equal(await page.evaluate(text=>window.donutImportRecording(text,'touch.json'),record),true);
 assert.equal(await page.evaluate(()=>window.donutDebug().source),'replay');
 assert.equal(await page.evaluate(()=>window.donutImportRecording('{bad','bad.json')),false);
 await page.locator('[data-panel=connect]').click();await page.locator('#demoReplay').click();await page.locator('#playReplay').click();await page.waitForTimeout(600);
 assert.equal(await page.evaluate(()=>window.donutDebug().replayPlaying),true);
 await page.screenshot({path:'build/ios-touch-preview.png',fullPage:true});
 assert.deepEqual(errors,[]);
 console.log(JSON.stringify({touchNotes:[first,second],nativeExportBridge:'passed',jsonImport:'passed',demoReplay:'passed',pageErrors:errors}));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
